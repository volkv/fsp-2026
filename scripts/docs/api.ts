// Overview of the public API for the documentation (section «Описание API»): the operations of the OpenAPI document by
// tag, with who may call each. The document itself is built by the application code (openapi.bundle.config.ts).
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { ROOT } from './licenses.ts';

export const API_FILE = join(ROOT, 'docs/submission/generated/api.md');

interface OpenApiOperation {
	operationId: string;
	summary: string;
	tags: string[];
	security?: Record<string, string[]>[];
	'x-permission'?: string;
}

interface OpenApi {
	openapi: string;
	info: { version: string };
	tags: { name: string; description: string }[];
	paths: Record<string, Record<string, OpenApiOperation>>;
}

const SCHEMES: Readonly<Record<string, string>> = {
	session: 'сессия',
	apiKey: 'ключ API',
	fspSignature: 'подпись ФСП',
	telegramSecret: 'секрет бота'
};

function accessOf(operation: OpenApiOperation): string {
	const security = operation.security ?? [];
	const ways = security.map((requirement) => {
		const names = Object.keys(requirement);
		if (names.length === 0) return 'без входа';
		return names
			.map((name) => {
				const label = SCHEMES[name];
				if (label === undefined) throw new Error(`${operation.operationId}: unknown security scheme ${name}`);
				return label;
			})
			.join(' + ');
	});
	if (ways.length === 0) throw new Error(`${operation.operationId}: no security requirement`);
	const permission = operation['x-permission'];
	return permission === undefined ? ways.join(' или ') : `${ways.join(' или ')}; право \`${permission}\``;
}

/** Builds the OpenAPI document with the application code and returns it as JSON text. */
export function buildOpenApiDocument(): string {
	execFileSync('pnpm', ['exec', 'vite', 'build', '--config', 'scripts/docs/openapi.bundle.config.ts'], {
		cwd: ROOT,
		stdio: ['ignore', 'inherit', 'inherit']
	});
	return execFileSync('node', [join(ROOT, 'build/docs-openapi/openapi-main.js')], {
		cwd: ROOT,
		encoding: 'utf8',
		maxBuffer: 64 * 1024 * 1024
	});
}

export function renderApi(document: OpenApi): string {
	const byTag = new Map<string, { method: string; path: string; operation: OpenApiOperation }[]>();
	let count = 0;
	for (const [path, item] of Object.entries(document.paths)) {
		for (const [method, operation] of Object.entries(item)) {
			const tag = operation.tags[0];
			if (tag === undefined) throw new Error(`${operation.operationId}: no tag`);
			const list = byTag.get(tag) ?? [];
			list.push({ method: method.toUpperCase(), path, operation });
			byTag.set(tag, list);
			count += 1;
		}
	}
	const lines = [
		'<!-- Generated by scripts/docs/build.ts from the OpenAPI document of the application; do not edit. -->',
		'',
		'## Перечень операций',
		'',
		`OpenAPI ${document.openapi}, версия API ${document.info.version}: ${count} операций. Схемы запросов и ответов, ` +
			'коды ошибок каждой операции — в документе `/api/v1/openapi.json` (рядом с этим файлом — `openapi.json`) и ' +
			'в интерактивной документации `/api/docs`.',
		''
	];
	for (const tag of document.tags) {
		const operations = byTag.get(tag.name);
		if (operations === undefined) continue;
		byTag.delete(tag.name);
		lines.push(
			`### ${tag.name}`,
			'',
			`${tag.description}.`,
			'',
			'| Метод и путь | Операция | Доступ |',
			'|----------------------------------------------|----------------------------|------------------------|',
			...operations.map(
				({ method, path, operation }) =>
					`| \`${method} ${path}\` | ${operation.summary.replace(/\|/g, '\\|')} | ${accessOf(operation)} |`
			),
			''
		);
	}
	if (byTag.size > 0) throw new Error(`operations under undeclared tags: ${[...byTag.keys()].join(', ')}`);
	return lines.join('\n');
}

/** Builds the document, writes the overview and returns the document text. */
export function generateApi(): { json: string; operations: number } {
	const json = buildOpenApiDocument();
	const document = JSON.parse(json) as OpenApi;
	mkdirSync(dirname(API_FILE), { recursive: true });
	writeFileSync(API_FILE, renderApi(document));
	const operations = Object.values(document.paths).reduce((sum, item) => sum + Object.keys(item).length, 0);
	return { json, operations };
}

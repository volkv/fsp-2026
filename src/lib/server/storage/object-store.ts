// Object storage of uploaded files (docs/domain.md, section 15.1): an S3-compatible bucket (SeaweedFS on the stand)
// reached only by the application and the worker. Requests are signed with AWS Signature V4 (aws4fetch); objects are
// addressed path-style, which S3-compatible servers accept without a DNS name per bucket. The bucket is never exposed
// to browsers: files are handed out through the application after an access check, so no presigned links exist.
import { AwsClient } from 'aws4fetch';
import { config } from '$lib/server/config';

/** The storage did not answer as expected: unreachable, refused the credentials, or returned an error status. */
export class StorageError extends Error {
	override name = 'StorageError';
	/** A repeat of the same request may succeed (connection failure, 5xx, 429). */
	readonly retryable: boolean;

	constructor(message: string, options: { retryable: boolean; cause?: unknown }) {
		super(message, { cause: options.cause });
		this.retryable = options.retryable;
	}
}

export interface StoredObject {
	body: ReadableStream<Uint8Array>;
	sizeBytes: number;
	contentType: string;
}

export interface ObjectStore {
	put(key: string, bytes: Uint8Array<ArrayBuffer>, contentType: string): Promise<void>;
	/** The object as a stream; `null` — there is no such object. */
	get(key: string, signal?: AbortSignal): Promise<StoredObject | null>;
	/** Removes the object; removing a missing object succeeds, so a repeated deletion is safe. */
	delete(key: string): Promise<void>;
	exists(key: string): Promise<boolean>;
}

export interface S3Settings {
	endpoint: string;
	region: string;
	accessKeyId: string;
	secretAccessKey: string;
	bucket: string;
}

/** Keys are generated by the application: a purpose prefix and a UUID, never a name the user chose. */
const KEY = /^[a-z_]+\/[0-9a-f-]{36}$/;

function assertKey(key: string): void {
	if (!KEY.test(key)) throw new Error(`storage key ${key} is not an application key`);
}

const retryableStatus = (status: number) => status >= 500 || status === 429;

export class S3ObjectStore implements ObjectStore {
	readonly #client: AwsClient;
	readonly #base: string;

	constructor(settings: S3Settings) {
		this.#client = new AwsClient({
			accessKeyId: settings.accessKeyId,
			secretAccessKey: settings.secretAccessKey,
			service: 's3',
			region: settings.region,
			// Two quick repeats of a 5xx or 429; anything longer is the caller's decision.
			retries: 2,
			initRetryMs: 50
		});
		this.#base = `${settings.endpoint.replace(/\/+$/, '')}/${settings.bucket}`;
	}

	#url(key: string): string {
		assertKey(key);
		return `${this.#base}/${key}`;
	}

	async #request(what: string, key: string, init: RequestInit): Promise<Response> {
		try {
			return await this.#client.fetch(this.#url(key), init);
		} catch (error) {
			if (init.signal?.aborted) throw error;
			throw new StorageError(`${what}: storage is unreachable`, { retryable: true, cause: error });
		}
	}

	async #failure(what: string, response: Response): Promise<StorageError> {
		// The error body is XML with a code and no user data; it is drained so the connection can be reused.
		await response.body?.cancel();
		return new StorageError(`${what}: storage answered ${response.status}`, {
			retryable: retryableStatus(response.status)
		});
	}

	async put(key: string, bytes: Uint8Array<ArrayBuffer>, contentType: string): Promise<void> {
		const response = await this.#request('put', key, {
			method: 'PUT',
			headers: { 'content-type': contentType, 'content-length': String(bytes.byteLength) },
			body: bytes
		});
		if (!response.ok) throw await this.#failure('put', response);
		await response.body?.cancel();
	}

	async get(key: string, signal?: AbortSignal): Promise<StoredObject | null> {
		const response = await this.#request('get', key, { method: 'GET', ...(signal ? { signal } : {}) });
		if (response.status === 404) {
			await response.body?.cancel();
			return null;
		}
		if (!response.ok || !response.body) throw await this.#failure('get', response);
		const length = Number(response.headers.get('content-length'));
		if (!Number.isSafeInteger(length) || length < 0) {
			await response.body.cancel();
			throw new StorageError('get: storage answered without a content length', { retryable: false });
		}
		return {
			body: response.body,
			sizeBytes: length,
			contentType: response.headers.get('content-type') ?? 'application/octet-stream'
		};
	}

	async delete(key: string): Promise<void> {
		const response = await this.#request('delete', key, { method: 'DELETE' });
		// S3 answers 204 for a removed and for a missing object alike.
		if (!response.ok) throw await this.#failure('delete', response);
		await response.body?.cancel();
	}

	async exists(key: string): Promise<boolean> {
		const response = await this.#request('head', key, { method: 'HEAD' });
		if (response.status === 404) return false;
		if (!response.ok) throw await this.#failure('head', response);
		return true;
	}
}

/** Reads a stored object whole; for the worker, which hands the bytes to the parser. */
export async function readObject(
	store: ObjectStore,
	key: string,
	signal?: AbortSignal
): Promise<Uint8Array<ArrayBuffer> | null> {
	const object = await store.get(key, signal);
	if (!object) return null;
	const bytes = new Uint8Array(await new Response(object.body).arrayBuffer());
	if (bytes.byteLength !== object.sizeBytes) {
		throw new StorageError('get: the object body is shorter than announced', { retryable: true });
	}
	return bytes;
}

let store: ObjectStore | undefined;

/** The configured bucket, created on first use so that `vite build` does not need the environment. */
export function objectStore(): ObjectStore {
	store ??= new S3ObjectStore(config().storage);
	return store;
}

export function translit(text: string): string {
	return text.toLowerCase().replace(/./gu, (ch) => TRANSLIT[ch] ?? ch);
}

/** Platform login in the usual `a_ivanov42` style. */
export function syntheticLogin(rnd: Random, name: SyntheticName): string {
	const base = `${translit(name.firstName).slice(0, 1)}_${translit(name.lastName)}`;
	return rnd.chance(0.6) ? `${base}${rnd.int(1, 99)}` : base;
}


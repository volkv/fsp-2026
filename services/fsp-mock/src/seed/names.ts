/** Rough weights: large regions field more athletes. */
const REGION_WEIGHTS: readonly number[] = REGIONS.map((_, i) => (i < 3 ? 6 : i < 10 ? 3 : i < 20 ? 2 : 1));

export interface SyntheticName {
	lastName: string;
	firstName: string;
	middleName: string | null;
	gender: 'male' | 'female';
}

export function syntheticName(rnd: Random): SyntheticName {
	const gender = rnd.chance(0.78) ? 'male' : 'female';
	const [maleSurname, femaleSurname] = rnd.pick(SURNAMES);
	const [, malePatronymic, femalePatronymic] = rnd.pick(PATRONYMIC_BASES);
	const withMiddle = rnd.chance(0.93);
	return gender === 'male'
		? {
				gender,
				lastName: maleSurname,
				firstName: rnd.pick(MALE_FIRST),
				middleName: withMiddle ? malePatronymic : null
			}
		: {
				gender,
				lastName: femaleSurname,
				firstName: rnd.pick(FEMALE_FIRST),
				middleName: withMiddle ? femalePatronymic : null
			};
}

export function syntheticRegion(rnd: Random): string {
	return rnd.weighted(REGIONS.map((r, i) => [r, REGION_WEIGHTS[i] ?? 1] as const));
}

